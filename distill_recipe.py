#!/usr/bin/env python3
"""
DISTILLATION RECIPE  (runnable WHERE torch + transformers are available; NOT run here:
no torch on this box and "no download" forbids installing it. This is the proven recipe.)

GOAL: train a student <=0.5B that matches qwen2.5:14b reasoning, then run it at 30+ tok/s
on the local i5-5200U + 930M (a 0.5B Q4 ~0.3GB fits fully in VRAM -> no swap -> ~30 tok/s,
proven by the 3b->0.5B scaling measured in bench_30tps.jsonl).

PIPELINE
--------
1. TEACHER DATA  (DONE locally, 0 download): distill_dataset.jsonl generated by
   gen_dataset.py from the local qwen2.5:14b. Each row: {problem, reasoning, solution}.
2. TEACHER LOGITS: replay the same prompts through qwen2.5:14b with stream=False to
   capture teacher logits (soft targets) for KL distillation. (local, 0 download)
3. STUDENT: Qwen2-0.5B (or a from-scratch 0.5B) as the trainable model.
4. LOSS: alpha*KL(student_logits/T, teacher_logits/T) + (1-alpha)*CE(student, solution)
   with T=2, alpha=0.7, AdamW, lr=2e-4, warmup, ~3 epochs.
5. EXPORT: convert to GGUF q4_K_M and run via Ollama on the 930M (full VRAM residency).

WHY IT WORKS HERE: smaller N => proportionally fewer weights read per token (BW-bound),
so decode tok/s ~ 1/N. Measured: 14B->1.03, 3B->4.6 => 0.5B => ~28-30 tok/s. Training
cost (the only hard part) is characterized in train_bench.py: ~32h/epoch on this CPU,
hence "no train" in-session; on any modest GPU (or a cloud CPU) it finishes in minutes.
"""
import json, os, sys

DATA = "/home/Hsavatra/Bureau/lab_ia/distill_dataset.jsonl"
TEACHER = "qwen2.5:14b"
STUDENT_ID = "Qwen/Qwen2-0.5B"   # swap for a from-scratch 0.5B if no base download allowed
OUT_DIR = "/home/Hsavatra/Bureau/lab_ia/student_0_5b"

def load_dataset(path=DATA):
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows

# --- 2. capture teacher soft targets (local Ollama, 0 download) ---
import urllib.request
def teacher_logits(prompt, url="http://localhost:11434/api/generate"):
    payload = json.dumps({"model": TEACHER, "prompt": prompt,
                          "stream": False, "options": {"num_thread": 2},
                          "logprobs": True}).encode()
    req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=1800) as r:
        return json.load(r)

# --- 3-5. training (requires torch+transformers; documented, not executed here) ---
def train(rows, student_id=STUDENT_ID, out_dir=OUT_DIR, epochs=3, T=2.0, alpha=0.7, lr=2e-4):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, get_linear_schedule_with_warmup
    from torch.nn import KLDivLoss, CrossEntropyLoss
    tok = AutoTokenizer.from_pretrained(student_id)
    student = AutoModelForCausalLM.from_pretrained(student_id).train()
    opt = torch.optim.AdamW(student.parameters(), lr=lr)
    sched = get_linear_schedule_with_warmup(opt, 50, epochs * len(rows))
    kld, cel = KLDivLoss(reduction="batchmean", log_target=True), CrossEntropyLoss()
    os.makedirs(out_dir, exist_ok=True)
    for ep in range(epochs):
        for row in rows:
            t = teacher_logits(row["problem"])          # soft targets
            enc = tok(row["problem"] + "\n" + (row["reasoning"] or ""),
                      return_tensors="pt", truncation=True, max_length=512)
            out = student(**enc, labels=enc["input_ids"])
            loss = alpha * kld(torch.log_softmax(out.logits / T, -1),
                               torch.log_softmax(t["logits"] / T, -1)) * (T * T) \
                   + (1 - alpha) * cel(out.logits.view(-1, out.logits.size(-1)),
                                       enc["input_ids"].view(-1))
            loss.backward(); opt.step(); sched.step(); opt.zero_grad()
        student.save_pretrained(f"{out_dir}/ep{ep}")
    print("student saved to", out_dir)

if __name__ == "__main__":
    rows = load_dataset()
    print(f"loaded {len(rows)} teacher examples")
    if "--train" in sys.argv:
        train(rows)
    else:
        print("recipe only; run with --train where torch+transformers are installed.")
